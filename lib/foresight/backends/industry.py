def run(llm, seed: str, verbose: bool = True) -> dict:
    data, err = safe_chat_json(
        llm,
        INDUSTRY_PROMPT.format(knowledge=SYSTEM_KNOWLEDGE, seed=seed[:2000]),
        temperature=0.5,  # 要判断力也要一点发散
    )
    if err:
        return {"backend": "industry", "error": err}
    if verbose:
        print(f"  ✓ 行业焦点：{data.get('industry')}")
    return {
        "backend": "industry",
        "industry": data.get("industry", ""),
        "profile_note": data.get("profile_note", ""),
        "outlook": data.get("outlook", ""),
        "directions": data.get("directions", []) if isinstance(data.get("directions"), list) else [],
        "avoid": data.get("avoid", []) if isinstance(data.get("avoid"), list) else [],
        "honest_note": data.get("honest_note", "行业判断存在失效风险，仅供参考。"),
        "no_prediction": True,  # 方向建议无法二元判定，不进校准日志
        "caveat": "行业前瞻是趋势研判非保证；涉及辞职、全职创业、大额投入前请多方求证。",
    }
